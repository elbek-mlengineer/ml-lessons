import numpy as np
from sklearn.tree import DecisionTreeClassifier, export_text

data = [
    *([[100, 30], 0] for _ in range(7)),
    *([[100, 30], 1] for _ in range(1)),
    *([[100, 50], 0] for _ in range(4)),
    *([[100, 50], 1] for _ in range(1)),
    *([[150, 30], 1] for _ in range(2)),
    *([[150, 50], 0] for _ in range(1)),
    *([[150, 50], 1] for _ in range(4)),
]

X = np.array([row[0] for row in data])
y = np.array([row[1] for row in data])
#  1  gini hisoblash
def gini(counts):
    total = sum(counts)
    return 1.0 - sum((c / total) ** 2 for c in counts)

root_gini = gini([12, 8])

gini_a_left = gini([11, 2])
gini_a_right = gini([1, 6])
weighted_gini_a = (13 / 20) * gini_a_left + (7 / 20) * gini_a_right
gain_a = root_gini - weighted_gini_a

gini_b_left = gini([7, 3])
gini_b_right = gini([5, 5])
weighted_gini_b = (10 / 20) * gini_b_left + (10 / 20) * gini_b_right
gain_b = root_gini - weighted_gini_b

print(f"Ildiz Gini: {root_gini:.4f}")
print(f"A bo'linish: Chap={gini_a_left:.4f}, O'ng={gini_a_right:.4f}, Og'irlikli={weighted_gini_a:.4f}, Gain={gain_a:.4f}")
print(f"B bo'linish: Chap={gini_b_left:.4f}, O'ng={gini_b_right:.4f}, Og'irlikli={weighted_gini_b:.4f}, Gain={gain_b:.4f}")

dt = DecisionTreeClassifier(criterion='gini', max_depth=1)
