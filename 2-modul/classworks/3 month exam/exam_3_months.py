# 3. TP, FP, FN va Recall hisoblash
p_vals = np.array([0.15, 0.35, 0.45, 0.62, 0.81])
y_true = np.array([0, 1, 0, 1, 1])

def evaluate_metrics(p, y, threshold):
    y_pred = (p >= threshold).astype(int)
    tp = np.sum((y == 1) & (y_pred == 1))
    fp = np.sum((y == 0) & (y_pred == 1))
    fn = np.sum((y == 1) & (y_pred == 0))
    recall = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    return tp, fp, fn, recall

print("3. TP, FP, FN VA RECALL HISOBLARI:")
for t in [0.5, 0.3]:
    tp, fp, fn, rec = evaluate_metrics(p_vals, y_true, t)
    print(f"   Chegara {t} -> TP: {tp}, FP: {fp}, FN: {fn}, Recall: {rec:.2f}")
print()

